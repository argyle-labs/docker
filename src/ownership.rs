/// One anonymous volume `label_volumes` would convert.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Planned {
    pub conversion: Conversion,
    /// The current anonymous volume; `None` when no container exists yet.
    pub old: Option<String>,
    /// Why it cannot be converted automatically.
    pub blocked: Option<String>,
}

/// The conversions for the anonymous volumes in `cfg` (the user's files)
/// that are not converted yet.
pub fn plan(
    cfg: &ComposeConfig,
    containers: &[ContainerSummary],
    converted: &[Conversion],
) -> Vec<Planned> {
    anonymous_volumes(cfg, containers)
        .into_iter()
        .filter(|a| {
            !converted
                .iter()
                .any(|c| c.service == a.service && c.target == a.target)
        })
        .map(|a| {
            let conversion = Conversion::new(&cfg.name, &a.service, &a.target);
            let (old, blocked) = match a.engine_names.as_slice() {
                [] => (None, None),
                [one] => (Some(one.clone()), None),
                many => (
                    None,
                    Some(format!(
                        "{} containers each hold their own volume here; convert by hand",
                        many.len()
                    )),
                ),
            };
            Planned {
                conversion,
                old,
                blocked,
            }
        })
        .collect()
}

pub fn planned_change(p: &Planned) -> PlannedChange {
    let c = &p.conversion;
    let detail = match (&p.blocked, &p.old) {
        (Some(why), _) => format!("not convertible: {why}"),
        (None, Some(old)) => format!(
            "stop '{}', copy {old} into new volume {} and verify it, declare it at {}, up, then remove {old} if no container uses it",
            c.service, c.name, c.target
        ),
        (None, None) => format!(
            "declare new volume {} at {} (no container yet, nothing to copy)",
            c.name, c.target
        ),
    };
    PlannedChange::new(c.key(), "convert").with_detail(detail)
}

/// The engine and compose steps of a migration. A seam so the sequencing and
/// its rollback are testable without a docker CLI.
pub trait Migrator: Send + Sync {
    fn stop<'a>(&'a self, service: &'a str) -> BoxFuture<'a, Result<()>>;
    fn start<'a>(&'a self, service: &'a str) -> BoxFuture<'a, Result<()>>;
    fn copy<'a>(&'a self, from: &'a str, to: &'a str) -> BoxFuture<'a, Result<()>>;
    /// A digest of every path's type, mode, owner, size and content.
    fn manifest<'a>(&'a self, volume: &'a str) -> BoxFuture<'a, Result<String>>;
    fn current_override(&self) -> Result<Option<String>>;
    fn write_override<'a>(&'a self, conversions: &'a [Conversion]) -> BoxFuture<'a, Result<()>>;
    fn restore_override(&self, previous: Option<&str>) -> Result<()>;
    fn up<'a>(&'a self, service: &'a str) -> BoxFuture<'a, Result<()>>;
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(crate = "plugin_toolkit::serde")]
#[schemars(crate = "plugin_toolkit::schemars")]
pub struct NotDone {
    pub item: String,
    pub reason: String,
}

#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(crate = "plugin_toolkit::serde")]
#[schemars(crate = "plugin_toolkit::schemars")]
pub struct Migrated {
    pub converted: Vec<String>,
    /// Old anonymous volumes removed after verification.
    pub removed: Vec<String>,
    /// Old volumes kept, and why.
    pub kept: Vec<NotDone>,
    pub skipped: Vec<NotDone>,
    pub failed: Vec<NotDone>,
}

/// Create the target volume with orca's labels, plus compose's project and
/// volume labels so compose adopts it as the stack's named volume.
pub async fn create_volume(
    docker: &Docker,
    project: &str,
    stack: &str,
    c: &Conversion,
) -> Result<()> {
    let mut labels: HashMap<String, String> =
        Labels::for_(OWNER_DOCKER, project, Some(&c.service), Some(stack))
            .with_mount(&c.target)
            .to_map()
            .into_iter()
            .collect();
    labels.insert(COMPOSE_PROJECT_LABEL.to_string(), project.to_string());
    labels.insert(COMPOSE_VOLUME_LABEL.to_string(), c.volume.clone());
    docker
        .create_volume(VolumeCreateRequest {
            name: Some(c.name.clone()),
            labels: Some(labels),
            ..Default::default()
        })
        .await
        .map_err(|e| anyhow::anyhow!("create volume {}: {e}", c.name))?;
    Ok(())
}

async fn volume_exists(docker: &Docker, name: &str) -> Result<bool> {
    match docker.inspect_volume(name).await {
        Ok(_) => Ok(true),
        Err(bollard::errors::Error::DockerResponseServerError {
            status_code: 404, ..
        }) => Ok(false),
        Err(e) => Err(anyhow::anyhow!("inspect volume {name}: {e}")),
    }
}

async fn referenced(docker: &Docker, volume: &str) -> Result<bool> {
    let filters = HashMap::from([("volume", vec![volume.to_string()])]);
    let users = docker
        .list_containers(Some(
            ListContainersOptionsBuilder::new()
                .all(true)
                .filters(&filters)
                .build(),
        ))
        .await
        .map_err(|e| anyhow::anyhow!("list containers using {volume}: {e}"))?;
    Ok(!users.is_empty())
}

async fn remove_volume(docker: &Docker, name: &str) -> Result<()> {
    docker
        .remove_volume(
            name,
            Some(RemoveVolumeOptionsBuilder::new().force(false).build()),
        )
        .await
        .map_err(|e| anyhow::anyhow!("remove volume {name}: {e}"))
}

/// Copy and verify one conversion into a volume this call creates. Returns
/// whether the target was created, so a failure can remove it.
async fn copy_one(
    docker: &Docker,
    m: &dyn Migrator,
    project: &str,
    stack: &str,
    p: &Planned,
    created: &mut Vec<String>,
) -> Result<()> {
    let c = &p.conversion;
    if volume_exists(docker, &c.name).await? {
        anyhow::bail!(
            "target volume {} already exists; remove it or convert by hand",
            c.name
        );
    }
    create_volume(docker, project, stack, c).await?;
    created.push(c.name.clone());
    if let Some(old) = &p.old {
        m.copy(old, &c.name).await?;
        let (want, got) = (m.manifest(old).await?, m.manifest(&c.name).await?);
        if want != got {
            anyhow::bail!(
                "verification failed: {} differs from {old} after the copy",
                c.name
            );
        }
    }
    Ok(())
}

/// Convert the confirmed `act` keys, one service at a time:
/// stop → create + copy + verify → declare in the override → up → remove
/// the old volume if no container references it. A failure before `up`
/// restores the previous override, removes the volumes it created and
/// starts the service again; the old volume is never touched.
pub async fn migrate(
    docker: &Docker,
    m: &dyn Migrator,
    project: &str,
    stack: &str,
    planned: &[Planned],
    act: &[String],
    converted: &[Conversion],
) -> Migrated {
    let mut out = Migrated::default();
    let mut by_service: BTreeMap<&str, Vec<&Planned>> = BTreeMap::new();
    for p in planned.iter().filter(|p| act.contains(&p.conversion.key())) {
        if let Some(why) = &p.blocked {
            out.skipped.push(NotDone {
                item: p.conversion.key(),
                reason: why.clone(),
            });
            continue;
        }
        by_service.entry(&p.conversion.service).or_default().push(p);
    }
    let mut conversions = converted.to_vec();
    for (svc, items) in by_service {
        let keys: Vec<String> = items.iter().map(|p| p.conversion.key()).collect();
        let fail = |out: &mut Migrated, reason: String| {
            out.failed.extend(keys.iter().map(|k| NotDone {
                item: k.clone(),
                reason: reason.clone(),
            }));
        };
        let previous = match m.current_override() {
            Ok(p) => p,
            Err(e) => {
                fail(&mut out, e.to_string());
                continue;
            }
        };
        let running = items.iter().any(|p| p.old.is_some());
        if running && let Err(e) = m.stop(svc).await {
            fail(&mut out, format!("stop: {e}"));
            if let Err(e) = m.start(svc).await {
                fail(&mut out, format!("start after failed stop: {e}"));
            }
            continue;
        }
        let mut created = Vec::new();
        let mut step: Result<()> = Ok(());
        for p in &items {
            step = copy_one(docker, m, project, stack, p, &mut created).await;
            if step.is_err() {
                break;
            }
        }
        if step.is_ok() {
            let mut next = conversions.clone();
            next.extend(items.iter().map(|p| p.conversion.clone()));
            step = m.write_override(&next).await;
            if step.is_ok() {
                conversions = next;
            }
        }
        if let Err(e) = step {
            let mut reason = e.to_string();
            if let Err(e) = m.restore_override(previous.as_deref()) {
                reason.push_str(&format!("; restoring the override failed: {e}"));
            }
            for name in &created {
                if let Err(e) = remove_volume(docker, name).await {
                    reason.push_str(&format!("; {e}"));
                }
            }
            if running && let Err(e) = m.start(svc).await {
                reason.push_str(&format!("; start: {e}"));
            }
            fail(&mut out, reason);
            continue;
        }
        if let Err(e) = m.up(svc).await {
            fail(
                &mut out,
                format!(
                    "up after the copy failed: {e}; the data is in the new volume, the old one is kept"
                ),
            );
            continue;
        }
        for p in items {
            out.converted.push(p.conversion.key());
            let Some(old) = &p.old else { continue };
            match referenced(docker, old).await {
                Ok(false) => match remove_volume(docker, old).await {
                    Ok(()) => out.removed.push(old.clone()),
                    Err(e) => out.kept.push(NotDone {
                        item: old.clone(),
                        reason: e.to_string(),
                    }),
                },
                Ok(true) => out.kept.push(NotDone {
                    item: old.clone(),
                    reason: "a container still references it".into(),
                }),
                Err(e) => out.kept.push(NotDone {
                    item: old.clone(),
                    reason: e.to_string(),
                }),
            }
        }
    }
    out
}

/// Builds the manifest inside the helper. `stat`/`find`/`sha256sum` are
/// busybox; paths are relative so source and target compare equal.
const MANIFEST_SCRIPT: &str = r#"set -eo pipefail; cd /v; { find . -exec stat -c '%n %F %a %u:%g' {} + | sort; find . -type f -exec stat -c '%n %s' {} + | sort; find . -type f -exec sha256sum {} + | sort -k2; } | sha256sum"#;

pub fn copy_args(from: &str, to: &str) -> Vec<String> {
    vec![
        "run".into(),
        "--rm".into(),
        "--network".into(),
        "none".into(),
        "--mount".into(),
        format!("type=volume,src={from},dst=/from,readonly"),
        "--mount".into(),
        format!("type=volume,src={to},dst=/to"),
        HELPER_IMAGE.into(),
        "sh".into(),
        "-c".into(),
        "cp -a /from/. /to/".into(),
    ]
}

pub fn manifest_args(volume: &str) -> Vec<String> {
    vec![
        "run".into(),
        "--rm".into(),
        "--network".into(),
        "none".into(),
        "--mount".into(),
        format!("type=volume,src={volume},dst=/v,readonly"),
        HELPER_IMAGE.into(),
        "sh".into(),
        "-c".into(),
        MANIFEST_SCRIPT.into(),
    ]
}

async fn docker_checked(args: &[String], what: &str) -> Result<String> {
    let mut cmd = plugin_toolkit::process::Command::new(crate::resolve_docker_bin()).args(args);
    if let Some(host) = crate::docker_host().await {
        cmd = cmd.env("DOCKER_HOST", host);
    }
    let out = cmd.output().await?;
    if !out.status.success {
        anyhow::bail!("{what}: {}", String::from_utf8_lossy(&out.stderr).trim());
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

/// The real [`Migrator`]: compose for the service, helper containers for the
/// data.
pub struct ComposeMigrator<'a> {
    pub row: &'a StackRow,
    pub docker: &'a Docker,
}

impl Migrator for ComposeMigrator<'_> {
    fn stop<'a>(&'a self, service: &'a str) -> BoxFuture<'a, Result<()>> {
        Box::pin(async move {
            self.row.compose()?.stop(&[service]).await?;
            Ok(())
        })
    }
    fn start<'a>(&'a self, service: &'a str) -> BoxFuture<'a, Result<()>> {
        Box::pin(async move {
            self.row.compose()?.start(&[service]).await?;
            Ok(())
        })
    }
    fn copy<'a>(&'a self, from: &'a str, to: &'a str) -> BoxFuture<'a, Result<()>> {
        Box::pin(async move {
            docker_checked(&copy_args(from, to), &format!("copy {from} to {to}")).await?;
            Ok(())
        })
    }
    fn manifest<'a>(&'a self, volume: &'a str) -> BoxFuture<'a, Result<String>> {
        Box::pin(async move {
            let digest =
                docker_checked(&manifest_args(volume), &format!("manifest of {volume}")).await?;
            if digest.is_empty() {
                anyhow::bail!("manifest of {volume} is empty");
            }
            Ok(digest)
        })
    }
    fn current_override(&self) -> Result<Option<String>> {
        let path = Path::new(&self.row.dir).join(ORCA_FILE);
        match std::fs::read_to_string(&path) {
            Ok(s) => Ok(Some(s)),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(anyhow::anyhow!("read {}: {e}", path.display())),
        }
    }
    fn write_override<'a>(&'a self, conversions: &'a [Conversion]) -> BoxFuture<'a, Result<()>> {
        Box::pin(async move {
            write_with(self.row, self.docker, Some(conversions)).await?;
            Ok(())
        })
    }
    fn restore_override(&self, previous: Option<&str>) -> Result<()> {
        let path = Path::new(&self.row.dir).join(ORCA_FILE);
        match previous {
            Some(text) => write_atomic(&path, text),
            None if path.exists() => {
                std::fs::remove_file(&path).with_context(|| format!("remove {}", path.display()))
            }
            None => Ok(()),
        }
    }
    fn up<'a>(&'a self, service: &'a str) -> BoxFuture<'a, Result<()>> {
        Box::pin(async move {
            up(self.row, &[service]).await?;
            Ok(())
        })
    }
}

