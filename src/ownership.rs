/// An anonymous volume of a stack service.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(crate = "plugin_toolkit::serde")]
#[schemars(crate = "plugin_toolkit::schemars")]
pub struct AnonymousVolume {
    pub service: String,
    pub target: String,
    /// The engine volumes behind it, one per container of the service.
    pub engine_names: Vec<String>,
}

fn service_containers<'a>(
    containers: &'a [ContainerSummary],
    service: &'a str,
) -> impl Iterator<Item = &'a ContainerSummary> {
    containers.iter().filter(move |c| {
        c.labels.as_ref().is_some_and(|l| {
            l.get(COMPOSE_SERVICE_LABEL).map(String::as_str) == Some(service)
                && l.get(COMPOSE_ONEOFF_LABEL).map(String::as_str) != Some("True")
        })
    })
}

/// Anonymous volume mounts of `cfg`, with the engine volume each service
/// container has there.
pub fn anonymous_volumes(
    cfg: &ComposeConfig,
    containers: &[ContainerSummary],
) -> Vec<AnonymousVolume> {
    let mut out = Vec::new();
    for (svc, s) in &cfg.services {
        for m in s.volumes.iter().filter(|m| m.is_anonymous()) {
            let engine_names = service_containers(containers, svc)
                .filter_map(|c| {
                    c.mounts.as_ref()?.iter().find_map(|mp| {
                        (mp.destination.as_deref() == Some(m.target.as_str()))
                            .then(|| mp.name.clone())
                            .flatten()
                    })
                })
                .collect();
            out.push(AnonymousVolume {
                service: svc.clone(),
                target: m.target.clone(),
                engine_names,
            });
        }
    }
    out
}

